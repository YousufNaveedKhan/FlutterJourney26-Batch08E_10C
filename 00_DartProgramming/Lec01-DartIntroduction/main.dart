void main() {
  // STRING
  var meraNaam = "Hassan";
  print("Name: $meraNaam");

  // INTEGER
  var meriAge = 22;
  print("Age: $meriAge");

  // DOUBLE ( DECIMAL )
  var meriHeight = 5.8;
  print("Height: $meriHeight");

  // BOOLEAN
  var isVerified = true;
  print("Is Verified: $isVerified");
}

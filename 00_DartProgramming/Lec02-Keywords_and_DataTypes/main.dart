// OOP ( OBJECT ORIENTED PROGRAMMING ) METHOD
// VOID => NO RETURN TYPE METHOD
void main() {
  // String
  var name = "asfnagtjsawjthna35236529036t23wt@@@@";
  print("Name: ${name}");

  // Integer
  var age = 21;
  print("Age: ${age}");

  // Decimal
  var height = 5.8;
  print("Height: ${height}");

  // Boolean
  var isVerified = true;
  print("Verified User: ${isVerified}");

  // Var vs Const
  var myName = "Fahad";
  print(myName);
  // Variable ko value reassign krrhe ho..
  myName = "Hassan Absar";
  print(myName);

  const myyName = "Alishba";
  print(myyName);

  // myyName = "Riba";

  // myName = 2;

  dynamic phone = "0331251235";
  print(phone);
  phone = "hammad";
  print(phone);
  phone = 65;
  print(phone);

  final namee = "Riba";
  // namee = "Alishba";
}
